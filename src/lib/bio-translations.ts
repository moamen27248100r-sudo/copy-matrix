type Translator = (key: string) => string;

export function translateBio(bio: string | null, t: Translator): string | null {
  if (!bio) return bio;
  const key = BIO_KEY_BY_ARABIC[bio];
  return key ? t(key) : bio;
}

export function useBioTranslator() {
  const t = useTranslations("Bios");
  return (bio: string | null) => translateBio(bio, t);
}

export async function getBioTranslator() {
  const t = await getTranslations("Bios");
  return (bio: string | null) => translateBio(bio, t);
}
