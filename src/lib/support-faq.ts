const NORMALIZE_MAP: Record<string, string> = {
  أ: "ا",
  إ: "ا",
  آ: "ا",
  ى: "ي",
  ة: "ه",
};

export function normalizeArabic(text: string): string {
  return text
    .split("")
    .map((ch) => NORMALIZE_MAP[ch] ?? ch)
    .join("")
    .toLowerCase()
    .trim();
}

const MATCH_THRESHOLD = 1;

function bestMatchIn(normalizedMessage: string, entries: FaqEntry[]): { entry: FaqEntry; score: number } | null {
  let best: { entry: FaqEntry; score: number } | null = null;
  for (const entry of entries) {
    let score = 0;
    for (const keyword of entry.keywords) {
      if (normalizedMessage.includes(normalizeArabic(keyword))) {
        score += 1;
      }
    }
    if (score > 0 && (!best || score > best.score)) {
      best = { entry, score };
    }
  }
  return best;
}

export function matchFaq(message: string): FaqEntry | null {
  const normalizedMessage = normalizeArabic(message);

  const topical = bestMatchIn(normalizedMessage, SUPPORT_FAQ);
  if (topical && topical.score >= MATCH_THRESHOLD) return topical.entry;

  const smallTalk = bestMatchIn(normalizedMessage, SMALL_TALK);
  if (smallTalk && smallTalk.score >= MATCH_THRESHOLD) return smallTalk.entry;

  return null;
}

